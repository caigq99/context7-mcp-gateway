const dictionaries = { 'zh-CN': zh, en };

export type Translate = (key: Text) => string;

const LanguageContext = createContext<{ locale: Locale; t: Translate; setLocale: (locale: Locale) => void } | null>(null);

function preferredLanguage(): Locale {
  try {
    const saved = window.localStorage.getItem('context7.locale');
    if (saved === 'zh-CN' || saved === 'en') return saved;
  } catch {
    // Storage may be disabled. The browser preference still works.
  }
  return navigator.language.startsWith('zh') ? 'zh-CN' : 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(preferredLanguage);
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  function selectLocale(next: Locale) {
    setLocale(next);
    try {
      window.localStorage.setItem('context7.locale', next);
    } catch {
      // A storage error does not prevent changing the language for this session.
    }
  }
  return (
    <LanguageContext.Provider value={{ locale, t: (key) => dictionaries[locale][key], setLocale: selectLocale }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const language = useContext(LanguageContext);
  if (!language) throw new Error('Missing language provider');
  return language;
}
